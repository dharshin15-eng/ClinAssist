import { apiClient } from './apiClient';
import type { Patient } from '../types';

export interface PatientRequestDto {
  patientId?: string;
  fullName: string;
  dateOfBirth: string; // ISO date string (YYYY-MM-DD)
  gender: string;
  phone: string;
  email?: string;
  address?: string;
  bloodGroup?: string;
}

export const patientService = {
  /**
   * Fetch all registered patient records.
   * GET /api/patients
   */
  async getPatients(): Promise<Patient[]> {
    return await apiClient.get<Patient[]>('/api/patients');
  },

  /**
   * Fetch a single patient record by MongoDB internal ID.
   * GET /api/patients/{id}
   */
  async getPatient(id: string): Promise<Patient> {
    return await apiClient.get<Patient>(`/api/patients/${id}`);
  },

  /**
   * Register a new patient record.
   * POST /api/patients
   * Note: patientId is auto-generated by backend if omitted.
   */
  async createPatient(data: PatientRequestDto): Promise<Patient> {
    return await apiClient.post<Patient>('/api/patients', data);
  },

  /**
   * Update an existing patient record by MongoDB internal ID.
   * PUT /api/patients/{id}
   */
  async updatePatient(id: string, data: PatientRequestDto): Promise<Patient> {
    return await apiClient.put<Patient>(`/api/patients/${id}`, data);
  },

  /**
   * Delete a patient record by MongoDB internal ID.
   * DELETE /api/patients/{id}
   */
  async deletePatient(id: string): Promise<void> {
    return await apiClient.delete<void>(`/api/patients/${id}`);
  }
};
