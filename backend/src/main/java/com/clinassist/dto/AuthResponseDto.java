package com.clinassist.dto;

import com.clinassist.entity.Role;

/**
 * Data Transfer Object returned upon successful authentication.
 */
public class AuthResponseDto {

    private String token;
    private String tokenType = "Bearer";
    private String id;
    private String email;
    private String fullName;
    private Role role;

    public AuthResponseDto() {
    }

    public AuthResponseDto(String token, String id, String email, String fullName, Role role) {
        this.token = token;
        this.id = id;
        this.email = email;
        this.fullName = fullName;
        this.role = role;
    }

    public String getToken() {
        return token;
    }

    public void setToken(String token) {
        this.token = token;
    }

    public String getTokenType() {
        return tokenType;
    }

    public void setTokenType(String tokenType) {
        this.tokenType = tokenType;
    }

    public String getId() {
        return id;
    }

    public void setId(String id) {
        this.id = id;
    }

    public String getEmail() {
        return email;
    }

    public void setEmail(String email) {
        this.email = email;
    }

    public String getFullName() {
        return fullName;
    }

    public void setFullName(String fullName) {
        this.fullName = fullName;
    }

    public Role getRole() {
        return role;
    }

    public void setRole(Role role) {
        this.role = role;
    }
}
